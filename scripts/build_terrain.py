PLAYABLE_BORDER = 2.5     # Scripts/bootstrap.galaxy gv_mapBoundsRegionsMinimumBorder
CELLFLAGS_HEADER = 32     # t3CellFlags: 32-byte header then worldSize^2 bytes, 1/cell
# Only bits 0x01/0x02 are ever set. A cell of 0 is void/water/off-map; any flagged
# cell (0x01 buildable-ish and/or 0x02 pathable) is real ground. Masking != 0 gives a
# consistent land/void mask across ALL maps — on Mar Sara it equals the old 0x02 test
# (65408 cells) but on water maps (Lost Tides/Duck) it correctly keeps the islands,
# where a bare 0x02 test would drop nearly everything and break the simulator.
CELLFLAG_GROUND_MASK = 0x03
CLIFFLEVEL_HEADER = 32    # t3SyncCliffLevel: 32-byte header then worldSize^2 int16, 1/cell
# Adjacent walkable cells step by <=40 along ramps but jump 64/128/192 across cliff
# faces. <=48 => same ramp/plateau; a larger jump is a cliff only ramps bridge.
CLIFF_STEP = 48
CELLATTR_HEADER = 4       # CellAttribute_Pnp: 4-byte header then worldSize^2 bytes, 1/cell
