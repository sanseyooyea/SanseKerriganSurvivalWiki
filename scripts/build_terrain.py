"""
Extract KS2 map terrain data for the /terrain web viewer, straight from map MPQs.

The published KS2 map re-bakes ONE terrain from a 22-map pool on each release. This
extractor works on any KS2 map archive (the live on-disk map, or a historical version
pulled from the Battle.net cache by scripts/harvest_terrains.py), so /terrain can offer
every terrain we've ever seen as a multi-map selector.

Per map it produces:
  - public/maps/<key>.png          the baked minimap (from Minimap.tga)
  - public/terrain/<key>.json      rock candidates + coord transform + packed pathing grid
And an index of all extracted maps:
  - data/terrain.json              { defaultMap, maps:[{key,name,nameZh,tileset,...}] }

Rock spawns are runtime-generated by Scripts/game/rocks.galaxy from the map's ramps:
the candidate pool is the set of regions named "Ramp<N>" (see gf_TerrainInit). Each game
shuffles them and places floor(rockProb * count), validated against pathing. We extract
the candidate pool + a passability grid + a cliff-level grid so the frontend simulator
(composables/useRockSimulator.ts) can reproduce the algorithm approximately.

Usage:  python scripts/build_terrain.py     (refresh the live map + rebuild index; run by build_all.py)
        python scripts/harvest_terrains.py  (one-time: pull every historical terrain from cache)
"""
